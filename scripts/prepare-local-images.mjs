import { createClient } from "@supabase/supabase-js";
import { config } from "dotenv";
import { execFile } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import sharp from "sharp";

const execFileAsync = promisify(execFile);

config({ path: ".env.local" });

const root = process.cwd();
const seedFile = path.join(root, "lib", "seed-images.ts");
const outputDir = path.join(root, "public", "media");
const mapFile = path.join(root, "lib", "generated", "local-image-map.ts");

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const supabaseKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!supabaseUrl || !supabaseKey) {
  throw new Error("Missing NEXT_PUBLIC_SUPABASE_URL or NEXT_PUBLIC_SUPABASE_ANON_KEY");
}

const supabase = createClient(supabaseUrl, supabaseKey);

const photoUrl = (id, width, height) =>
  `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?auto=compress&cs=tinysrgb&w=${width}&h=${height}&fit=crop`;

function pexelsUrlFromSeed(text) {
  const urls = new Set();
  const pattern = /photo\((\d+),\s*(\d+),\s*(\d+)\)/g;
  for (const match of text.matchAll(pattern)) {
    urls.add(photoUrl(Number(match[1]), Number(match[2]), Number(match[3])));
  }
  return [...urls];
}

async function databaseUrls() {
  const [settings, hero, collections] = await Promise.all([
    supabase.from("site_settings").select("logo_url").maybeSingle(),
    supabase.from("hero").select("image_url").maybeSingle(),
    supabase.from("collections").select("slug,image_url"),
  ]);

  if (settings.error) throw settings.error;
  if (hero.error) throw hero.error;
  if (collections.error) throw collections.error;

  const urls = [];
  if (settings.data?.logo_url) urls.push(settings.data.logo_url);
  if (hero.data?.image_url) urls.push(hero.data.image_url);
  for (const collection of collections.data ?? []) {
    if (collection.image_url) urls.push(collection.image_url);
  }
  return urls;
}

function outputName(url) {
  if (url.includes("images.pexels.com/photos/")) {
    const id = url.match(/\/photos\/(\d+)\//)?.[1] ?? "photo";
    const width = url.match(/[?&]w=(\d+)/)?.[1] ?? "w";
    const height = url.match(/[?&]h=(\d+)/)?.[1] ?? "h";
    return `pexels-${id}-${width}x${height}.webp`;
  }
  if (url.includes("/branding/")) return "brand.webp";
  if (url.includes("/hero/")) return "hero.webp";
  if (url.includes("/collections/")) {
    const slug = url.split("/").pop()?.split(".")[0]?.split("-").slice(0, -1).join("-");
    return `collection-${slug || "image"}.webp`;
  }
  return `image-${Buffer.from(url).toString("base64url").slice(0, 16)}.webp`;
}

function maxWidthFor(url) {
  if (url.includes("/branding/")) return 512;
  if (url.includes("/hero/")) return 1600;
  if (url.includes("/collections/")) return 800;
  const width = Number(url.match(/[?&]w=(\d+)/)?.[1] ?? 0);
  const height = Number(url.match(/[?&]h=(\d+)/)?.[1] ?? 0);
  if (width >= height * 1.5) return 1600;
  return 900;
}

async function download(url) {
  const { stdout } = await execFileAsync(
    "curl.exe",
    ["-L", "--fail", "--silent", "--show-error", "--max-time", "60", url],
    { encoding: "buffer", maxBuffer: 32 * 1024 * 1024 },
  );
  return stdout;
}

async function main() {
  const seedText = await readFile(seedFile, "utf8");
  const urls = [...new Set([...pexelsUrlFromSeed(seedText), ...(await databaseUrls())])];
  await mkdir(outputDir, { recursive: true });
  await mkdir(path.dirname(mapFile), { recursive: true });

  const map = {};
  for (const url of urls) {
    const name = outputName(url);
    const source = await download(url);
    const width = maxWidthFor(url);
    await sharp(source)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 78, effort: 6 })
      .toFile(path.join(outputDir, name));
    map[url] = `/media/${name}`;
    console.log(`${name}  ${(source.length / 1024).toFixed(0)} KB source`);
  }

  const contents =
    "// Generated by scripts/prepare-local-images.mjs. Do not edit by hand.\n" +
    "export const LOCAL_IMAGE_MAP: Record<string, string> = " +
    `${JSON.stringify(Object.fromEntries(Object.entries(map).sort()), null, 2)};\n`;
  await writeFile(mapFile, contents, "utf8");
  console.log(`Wrote ${Object.keys(map).length} local image mappings.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
